MODULE = Path(__file__).resolve().parents[2]/'tools/audit_release.py'


def implementation():
    if not MODULE.is_file():
        pytest.fail('release audit is not implemented')
    spec = importlib.util.spec_from_file_location('dcrc_release_audit_under_test',MODULE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def git(root,*args):
    result = subprocess.run(['git','-C',str(root),*args],capture_output=True,check=True)
    return result.stdout


def repo(tmp_path,files):
    root=tmp_path/'synthetic-repo';root.mkdir();git(root,'init','--quiet')
    for rel,data in files.items():
        p=root/rel;p.parent.mkdir(parents=True,exist_ok=True)
        p.write_bytes(data.encode('utf8')if isinstance(data,str)else data)
    provenance(root,files)
    return root


def provenance(root,paths):
    records={}
    for rel in paths:
        data=(root/rel).read_bytes()
        records[rel]={'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'category':'O','license':'MIT',
                      'source':{'url':'https://github.com/SandstoneDev/DCRC','revision':'own-synthetic-fixture','path':rel},
                      'review':'Own synthetic test content, no game or SDK fixture.'}
    p=root/'audit/PROVENANCE.json';p.parent.mkdir(exist_ok=True)
    p.write_text(json.dumps({'schema':1,'files':records}),encoding='utf8')


def rules(report):
    return {row['rule']for row in report['findings']}


