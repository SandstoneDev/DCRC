def test_history_scans_dangling_blobs_and_commit_message_without_real_commits(tmp_path):
    mod=implementation();root=repo(tmp_path,{'own.py':'x=1\n'});real_git=mod._git
    oid1,oid2='1'*40,'2'*40
    secret='ghp_'+'D'*36
    blob=('value='+repr(secret)+'\n').encode()
    commit=('tree '+'0'*40+'\n\naccidental '+secret+'\n').encode()
    def synthetic_git(folder,*args,**kw):
        if args and args[0]=='rev-list':return b''
        if '--batch-all-objects' in args:return (oid1+' blob '+str(len(blob))+'\n'+oid2+' commit '+str(len(commit))+'\n').encode()
        if '--batch' in args:
            return ((oid1+' blob '+str(len(blob))+'\n').encode()+blob+b'\n'+
                    (oid2+' commit '+str(len(commit))+'\n').encode()+commit+b'\n')
        return real_git(folder,*args,**kw)
    with patch.object(mod,'_git',side_effect=synthetic_git):report=mod.audit(root,history=True)
    assert not report['ok']
    assert report['scope']['history_blobs_scanned']==1
    assert report['scope']['history_commits_scanned']==1
    assert sum(row['rule']=='credential'for row in report['findings'])==2
    assert secret not in json.dumps(report)
    assert report['scope']['history_provenance']=='not validated; content policy only'


