class AuditError(Exception):
    pass


def _git(root, *args, input=None):
    env = dict(os.environ)
    for key in ('GIT_DIR','GIT_WORK_TREE','GIT_INDEX_FILE','GIT_OBJECT_DIRECTORY','GIT_ALTERNATE_OBJECT_DIRECTORIES'):
        env.pop(key, None)
    command = ['git','--no-optional-locks','--no-replace-objects','-c','core.fsmonitor=false',
               '-c','core.untrackedCache=false','-C',str(root),*args]
    p = subprocess.run(command,input=input,stdout=subprocess.PIPE,stderr=subprocess.PIPE,env=env)
    if p.returncode:
        raise AuditError('git_read_failed')
    return p.stdout


def _path(value):
    if not isinstance(value,str) or not value or '\\' in value or ':' in value or '\0' in value:
        raise AuditError('unsafe_path')
    p = PurePosixPath(value)
    if p.is_absolute() or str(p)!=value or any(s in ('.','..','.git') for s in p.parts):
        raise AuditError('unsafe_path')
    for part in p.parts:
        if part.endswith(('.', ' ')) or re.fullmatch(r'(?i)(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\..*)?',part):
            raise AuditError('unsafe_path')
    return p


def _reparse(path):
    try:
        info = path.lstat()
        return path.is_symlink() or bool(getattr(info,'st_file_attributes',0) & 0x400)
    except FileNotFoundError:
        return False


def _filesystem_path(root, relative):
    p = root
    for part in _path(relative).parts:
        p = p/part
        if _reparse(p):
            raise AuditError('reparse_point')
    if not p.resolve().is_relative_to(root):
        raise AuditError('unsafe_path')
    return p


def _label(path):
    text = str(path)
    if TOKEN.search(text) or ASSIGNMENT.search(text) or HOST_PATH.search(text):
        return '<redacted-path:'+hashlib.sha256(text.encode('utf8',errors='replace')).hexdigest()[:12]+'>'
    return text


def _finding(findings,path,rule,data=None,line=None):
    row = {'file':_label(path),'rule':rule,'line':line,
           'sha256':hashlib.sha256(data).hexdigest() if data is not None else None}
    if row not in findings:
        findings.append(row)


def _index(root):
    rows = {}
    for raw in _git(root,'ls-files','--stage','-z').split(b'\0'):
        if not raw:
            continue
        try:
            info,path = raw.split(b'\t',1)
            mode,oid,stage = info.decode('ascii').split()
            path = path.decode('utf8')
        except (ValueError,UnicodeError):
            raise AuditError('invalid_git_index')
        rows[path] = (mode,oid,int(stage))
    return rows


def _batch(root, objects):
    """Bound each cat-file response batch by declared source-object sizes."""
    group, size = [], 0
    def read(records):
        body = _git(root,'cat-file','--batch',input=('\n'.join(r[0] for r in records)+'\n').encode('ascii'))
        cursor = 0
        for oid,kind,want in records:
            end = body.find(b'\n',cursor)
            if end < 0:
                raise AuditError('invalid_git_object')
            header = body[cursor:end].decode('ascii').split()
            if header != [oid,kind,str(want)]:
                raise AuditError('invalid_git_object')
            cursor = end+1
            data = body[cursor:cursor+want]
            if len(data)!=want or body[cursor+want:cursor+want+1]!=b'\n':
                raise AuditError('invalid_git_object')
            cursor += want+1
            yield oid,kind,data
        if cursor != len(body):
            raise AuditError('invalid_git_object')
    for record in objects:
        if group and size+record[2] > 16*1024*1024:
            yield from read(group)
            group,size = [],0
        group.append(record);size += record[2]
    if group:
        yield from read(group)


def _python_string_lines(text):
    lines = set()
    try:
        for token in tokenize.generate_tokens(io.StringIO(text).readline):
            if token.type == tokenize.STRING:
                lines.update(range(token.start[0],token.end[0]+1))
    except (tokenize.TokenError,IndentationError,SyntaxError):
        pass
    return lines


def _content(path,data,findings):
    label = str(path)
    normalized = label.casefold()
    if any(normalized==p or normalized.endswith('/'+p) for p in DENIED_PATHS):
        _finding(findings,label,'excluded_derived_path',data,1)
    if hashlib.sha256(data).hexdigest() in DENIED_SHA256:
        _finding(findings,label,'excluded_derived_hash',data,1)
    suffix = PurePosixPath(label).suffix.casefold()
    if suffix in BLOCKED_EXT:
        _finding(findings,label,'forbidden_payload_extension',data,1)
    magic = (b'MZ',b'\x7fELF',b'\0PBP',b'~PSP',b'SEGA SEGAKATANA',b'GBIX',b'PVRT',b'AFS\0',b'SMLT',b'SA1N')
    if any(data.startswith(value) for value in magic):
        _finding(findings,label,'binary_magic',data,1)
    # Reviewed own/open image assets are possible source resources. Their rights
    # still rely on truthful provenance; an image signature proves no authorship.
    image = ((suffix=='.png' and data.startswith(b'\x89PNG\r\n\x1a\n')) or
             (suffix in ('.jpg','.jpeg') and data.startswith(b'\xff\xd8\xff')) or
             (suffix=='.ico' and data.startswith(b'\0\0\1\0')))
    try:
        text = data.decode('utf-8-sig')
    except UnicodeDecodeError:
        if not image:
            text_suffixes = {'.py','.c','.h','.s','.json','.md','.txt','.toml','.ini','.cfg','.ps1',
                             '.sh','.lua','.yml','.yaml','.html','.css','.patch','.svg','.tsv','.tape','.check'}
            rule = 'non_utf8_text' if suffix in text_suffixes and b'\0' not in data else 'binary_or_non_utf8_payload'
            _finding(findings,label,rule,data,1)
        # ASCII secrets/paths in binary metadata remain in scope. Latin1 gives
        # a one-byte mapping without hiding bytes on a failed UTF8 decode.
        text = data.decode('latin1')
    if '\0' in text and not image:
        _finding(findings,label,'binary_or_non_utf8_payload',data,1)
    for pattern,rule in ((TOKEN,'credential'),(ASSIGNMENT,'credential'),(HOST_PATH,'host_absolute_path')):
        for match in pattern.finditer(text):
            if rule=='host_absolute_path' and re.match(r'(?i)^[A-Z]:',match.group()):
                tail = match.group()[2:].strip('/\\')
                if not tail or tail=='...':
                    continue  # drive-prefix checks and documented placeholders
            _finding(findings,label,rule,data,text.count('\n',0,match.start())+1)
    literal_lines = _python_string_lines(text) if suffix=='.py' else set()
    for match in GENERATED.finditer(text):
        line = text.count('\n',0,match.start())+1
        # Generator/parser source may legitimately print a banner as a string.
        if line not in literal_lines:
            _finding(findings,label,'generated_game_code',data,line)


def _manifest(data, findings):
    if data is None:
        _finding(findings,MANIFEST,'manifest_missing')
        return {}
    try:
        def unique(pairs):
            result = {}
            for key,value in pairs:
                if key in result:
                    raise ValueError('duplicate key')
                result[key] = value
            return result
        def invalid_constant(value):
            raise ValueError('non-JSON constant')
        doc = json.loads(data,object_pairs_hook=unique,parse_constant=invalid_constant)
        if not isinstance(doc,dict) or type(doc.get('schema'))is not int or doc['schema']!=1 or not isinstance(doc.get('files'),dict):
            raise ValueError()
    except (ValueError,UnicodeError,TypeError):
        _finding(findings,MANIFEST,'provenance_schema',data,1)
        return {}
    records = {}
    folded = set()
    for path,entry in doc['files'].items():
        try:
            _path(path)
        except AuditError:
            _finding(findings,MANIFEST,'unsafe_path',data,1)
            continue
        if path.casefold() in folded:
            _finding(findings,MANIFEST,'provenance_case_collision',data,1)
        folded.add(path.casefold())
        records[path] = entry
        if not isinstance(entry,dict):
            _finding(findings,path,'provenance_schema',data,1)
            continue
        if entry.get('category') not in ('O','F','T'):
            _finding(findings,path,'nonredistributable_category',data,1)
        licence = entry.get('license')
        if not isinstance(licence,str) or not licence.strip() or NONREDISTRIBUTABLE.search(licence):
            _finding(findings,path,'nonredistributable_license',data,1)
        if not entry.get('review') or not isinstance(entry['review'],(str,dict)):
            _finding(findings,path,'provenance_review_missing',data,1)
        source = entry.get('source')
        valid_source = isinstance(source,dict) and all(isinstance(source.get(k),str) and source[k].strip() for k in ('url','revision','path'))
        if valid_source:
            try:
                url = urlsplit(source['url'])
                valid_source = url.scheme=='https' and bool(url.hostname) and url.username is None and url.password is None and not any(ord(c)<33 for c in source['url'])
                url.port  # also reject malformed port values
                _path(source['path'])
            except (AuditError,ValueError):
                valid_source = False
        if not valid_source:
            _finding(findings,path,'provenance_source_invalid',data,1)
        if path!=MANIFEST and (not isinstance(entry.get('sha256'),str) or not SHA.fullmatch(entry['sha256']) or type(entry.get('bytes'))is not int or entry['bytes']<0):
            _finding(findings,path,'provenance_digest_invalid',data,1)
    return records


def _history(root,index,findings,scope):
    names = {oid:path for path,(mode,oid,stage) in index.items()}
    for raw in _git(root,'rev-list','--objects','--all').splitlines():
        fields = raw.split(b' ',1)
        if len(fields)==2:
            try:
                path = fields[1].decode('utf8')
                if not path.startswith('"'):
                    names.setdefault(fields[0].decode('ascii'),path)
            except UnicodeError:
                pass
    objects = []
    for raw in _git(root,'cat-file','--batch-all-objects','--batch-check=%(objectname) %(objecttype) %(objectsize)').splitlines():
        try:
            oid,kind,size = raw.decode('ascii').split();size=int(size)
            if not re.fullmatch(r'[0-9a-f]{40}|[0-9a-f]{64}',oid) or size<0:
                raise ValueError()
        except (ValueError,UnicodeError):
            raise AuditError('invalid_git_object')
        if kind not in ('blob','commit'):
            continue
        label = 'history/'+names.get(oid,kind+'/'+oid)
        if size > MAX_FILE:
            _finding(findings,label,'oversized_object_not_scanned')
            scope['history_oversized_objects'] += 1
        else:
            objects.append((oid,kind,size))
    for oid,kind,data in _batch(root,objects):
        label = 'history/'+names.get(oid,kind+'/'+oid)
        if kind=='commit':
            # Raw commit is inspected too: identities/signatures must not hide a
            # credential or machine path outside the message body.
            scope['history_commits_scanned'] += 1
        else:
            scope['history_blobs_scanned'] += 1
        _content(label,data,findings)


def audit(root, staged=False, history=False):
    findings = []
    scope = {'view':'index' if staged else 'working_tree','working_tree_scanned':not staged,
             'empty_index':False,'history_requested':bool(history),'history_blobs_scanned':0,
             'history_commits_scanned':0,'history_oversized_objects':0,
             'history_provenance':'not validated; content policy only'}
    checked = 0
    try:
        root = Path(root).expanduser().absolute()
        if any(_reparse(p) for p in (*reversed(root.parents),root)):
            raise AuditError('reparse_root')
        root = root.resolve()
        index = _index(root)
        scope['empty_index'] = staged and not index
        if staged:
            names = set(index)
        else:
            extra = _git(root,'ls-files','--others','--exclude-standard','-z')
            names = set(index) | {p.decode('utf8')for p in extra.split(b'\0')if p}
        payloads = {}
        casefolded = set()
        for name in sorted(names):
            try:
                _path(name)
                if name.casefold() in casefolded:
                    raise AuditError('path_case_collision')
                casefolded.add(name.casefold())
                if name in index:
                    mode,oid,stage = index[name]
                    if stage:
                        raise AuditError('unmerged_index')
                    if mode=='120000':
                        raise AuditError('reparse_point')
                    if mode not in ('100644','100755'):
                        raise AuditError('unsupported_git_mode')
                if staged:
                    size = int(_git(root,'cat-file','-s',index[name][1]))
                    if size > MAX_FILE:
                        raise AuditError('oversized_file_not_scanned')
                    data = _git(root,'cat-file','blob',index[name][1])
                else:
                    path = _filesystem_path(root,name)
                    if not path.is_file():
                        raise AuditError('missing_or_nonregular_file')
                    if path.stat().st_size > MAX_FILE:
                        raise AuditError('oversized_file_not_scanned')
                    with path.open('rb') as stream:
                        data = stream.read(MAX_FILE+1)
                    if len(data)>MAX_FILE:
                        raise AuditError('oversized_file_not_scanned')
                payloads[name] = data
                _content(name,data,findings)
                checked += 1
            except AuditError as error:
                _finding(findings,name,str(error))
            except (OSError,UnicodeError,ValueError):
                _finding(findings,name,'file_read_failed')
        if not (staged and not index):
            records = _manifest(payloads.get(MANIFEST),findings)
            for name,data in payloads.items():
                if name==MANIFEST:
                    continue  # content scanned; circular self-digest is exempt
                entry = records.get(name)
                if not isinstance(entry,dict):
                    _finding(findings,name,'unknown_provenance',data)
                    continue
                if entry.get('sha256')!=hashlib.sha256(data).hexdigest():
                    _finding(findings,name,'hash_mismatch',data)
                if type(entry.get('bytes'))is not int or entry.get('bytes')!=len(data):
                    _finding(findings,name,'size_mismatch',data)
        if history:
            _history(root,index,findings,scope)
    except AuditError as error:
        _finding(findings,'<repository>',str(error))
    except (OSError,UnicodeError,ValueError):
        _finding(findings,'<repository>','audit_read_failed')
    return {'ok':not findings,'status':'PASS' if not findings else 'FAIL','files_checked':checked,
            'findings':findings,'scope':scope,
            'limits':['Provenance records are reviewed claims, not proof of ownership or independent implementation.',
                      'Historical content is scanned, but historical per-blob provenance/licences are not validated.',
                      'Oversized or unreadable objects fail closed; their complete contents are not scanned.',
                      'An empty index pass covers zero files and says nothing about the working tree.',
                      'Image authorship, manually transcribed code and unknown encoded payloads require human review.']}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path('.'))
    parser.add_argument('--staged',action='store_true')
    parser.add_argument('--history',action='store_true')
    parser.add_argument('--report',type=Path)
    args = parser.parse_args(argv)
    report = audit(args.root,staged=args.staged,history=args.history)
    text = json.dumps(report,indent=2,ensure_ascii=True)+'\n'
    if args.report:
        try:
            args.report.parent.mkdir(parents=True,exist_ok=True)
            args.report.write_text(text,encoding='utf8',newline='\n')
        except OSError:
            report['ok'],report['status'] = False,'FAIL'
            _finding(report['findings'],'<report>','report_write_failed')
            text = json.dumps(report,indent=2,ensure_ascii=True)+'\n'
    sys.stdout.write(text)
    return 0 if report['ok'] else 1


